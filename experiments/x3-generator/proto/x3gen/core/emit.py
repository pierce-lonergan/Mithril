"""Generation driver: meanings x schedules -> C translation units and a header (library L).

Provenance (DESIGN 5.3): every file records the generator hash (SHA-256 over the x3gen core and isa
sources, standing in for a commit until the prototype is committed), the meaning hash, the schedule
hash and the target, and says "do not edit; regenerate with x3gen".
"""

import hashlib
import json
import pathlib

from . import lower as lowering
from .lp import Program
from .printer import print_program

ROOT = pathlib.Path(__file__).resolve().parents[1]


def sha_files(paths):
    h = hashlib.sha256()
    for p in sorted(paths):
        rel = p.relative_to(ROOT).as_posix()
        h.update(rel.encode() + b"\0" + hashlib.sha256(p.read_bytes()).digest())
    return h.hexdigest()


def generator_hash():
    files = [p for d in ("core", "isa") for p in (ROOT / d).glob("*.py")]
    return sha_files(files)


def file_hash(path):
    return hashlib.sha256(pathlib.Path(path).read_bytes()).hexdigest()


def build(meanings, schedules, meaning_file, schedule_files):
    """meanings: {fmt: Kernel}; schedules: {isa: function(kernel) -> Schedule}.
    Returns ({filename: text}, report)."""
    gen = generator_hash()
    mh = file_hash(meaning_file)
    out, report = {}, {"generator_sha256": gen, "meaning_sha256": mh, "variants": []}
    slot = next(iter(meanings.values())).slot
    decls = []
    for isa, fn in schedules.items():
        sh = file_hash(schedule_files[isa])
        funcs = []
        for fmt, k in meanings.items():
            s = fn(k)
            name = slot.name_pattern.format(fmt=fmt, isa=isa)
            funcs.append(lowering.lower(s, name))
            decls.append(name)
            report["variants"].append(
                {
                    "name": name,
                    "isa": isa,
                    "meaning": k.name,
                    "schedule_sha256": sh,
                    "primitives": s.log.apps,
                }
            )
        simd = isa != "scalar"
        header = [
            "/* Generated by x3gen (X3 prototype). Do not edit; regenerate with x3gen. */",
            "/* generator sha256 %s */" % gen,
            "/* meaning   sha256 %s */" % mh,
            "/* schedule  sha256 %s */" % sh,
            "/* target %s */" % isa,
        ]
        includes = ('"%s"' % slot.header, "<string.h>")
        prelude = ["#include <immintrin.h>"] if simd else []
        prog = Program(isa, slot.simd_guard if simd else None, includes, prelude, funcs, header)
        out["x3_q_%s.c" % isa] = print_program(prog)
    params = ", ".join("%s%s%s" % (t, "" if t.endswith("*") else " ", n) for t, n in slot.params)
    h = [
        "/* Generated by x3gen (X3 prototype). Do not edit; regenerate with x3gen. */",
        "/* generator sha256 %s */" % gen,
        "#ifndef X3_GEN_H",
        "#define X3_GEN_H",
        '#include "%s"' % slot.header,
        "",
    ]
    for d in decls:
        h.append("void %s(%s);" % (d, params))
    h += ["", "#endif /* X3_GEN_H */", ""]
    out["x3_gen.h"] = "\n".join(h)
    for name, text in out.items():
        report.setdefault("files", {})[name] = hashlib.sha256(text.encode()).hexdigest()
    return out, report


def write(out, report, out_dir):
    d = pathlib.Path(out_dir)
    d.mkdir(parents=True, exist_ok=True)
    for name, text in out.items():
        (d / name).write_bytes(text.encode())
    (d / "x3gen_report.json").write_bytes(
        (json.dumps(report, indent=1, default=str) + "\n").encode()
    )
