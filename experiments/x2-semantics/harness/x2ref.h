/* x2ref.h -- the C reference interpreter of the X2 semantics table (FUZZ-DESIGN.md sec. 4).
 *
 * A line-by-line port of semantics/{bits,fpenv,rounding,fp_ops,int_ops,vec}.py and of the builders
 * of semantics/table.py. Exact integer arithmetic only: no host floating point touches a result bit.
 * It is validated against the Python reference (validate_interp.py) before it is used, and its
 * source hash is named in every result file it produces (FUZZ-DESIGN sec. 1).
 *
 * Exactness argument (also in README.md): ADD/SUB align significands exactly when the exponent gap
 * is <= 40 (fits in 64 bits); for a larger gap the smaller operand is replaced by a sticky unit
 * 2^(Ex-40), which keeps the exact sum strictly inside the same interval between consecutive
 * rounding boundaries (representable values and midpoints are >= 2^(Ex-2) apart near X, the true
 * contribution and the sticky unit are both nonzero and < 2^(Ex-17)). MUL is exact in 48 bits. DIV
 * normalises both significands to [2^23, 2^24), forms a 41-bit quotient and a sticky bit from the
 * remainder; rounding boundaries are >= 2^15 quotient units apart, so the sticky stand-in rounds
 * exactly like the true quotient. Tininess is detected after rounding, as in rounding.py.
 */
#ifndef X2REF_H
#define X2REF_H
#include <stdint.h>

#define X2_IE 0x01u
#define X2_DE 0x02u
#define X2_ZE 0x04u
#define X2_OE 0x08u
#define X2_UE 0x10u
#define X2_PE 0x20u

#define X2_RNE 0
#define X2_RD 1
#define X2_RU 2
#define X2_RZ 3

#define X2_MXCSR_DEFAULT 0x1F80u

typedef struct {
    int rc, daz, ftz, sae, er;   /* er: 1 if {er} supplied rc (then sae = 1) */
    uint32_t mxcsr;
} x2env;

/* Returns 0 on success, -1 if the MXCSR is outside the model (an unmasked exception or reserved bits). */
int x2_env_make(x2env *e, uint32_t mxcsr, int er /* -1 none, else 0..3 */, int sae);

/* binary32 helpers */
int x2_is_nan(uint32_t b);
int x2_is_snan(uint32_t b);
int x2_is_denormal(uint32_t b);

/* FP lane functions (fp_ops.py). Each returns the result bits and ORs its flags into *fl. */
uint32_t x2_add(uint32_t a, uint32_t b, const x2env *e, uint32_t *fl);
uint32_t x2_sub(uint32_t a, uint32_t b, const x2env *e, uint32_t *fl);
uint32_t x2_mul(uint32_t a, uint32_t b, const x2env *e, uint32_t *fl);
uint32_t x2_div(uint32_t a, uint32_t b, const x2env *e, uint32_t *fl);
uint32_t x2_max(uint32_t a, uint32_t b, const x2env *e, uint32_t *fl);
uint32_t x2_min(uint32_t a, uint32_t b, const x2env *e, uint32_t *fl);

#define X2_REL_LT 1
#define X2_REL_EQ 2
#define X2_REL_GT 4
#define X2_REL_UN 8
int x2_relation(uint32_t a, uint32_t b, const x2env *e, int signalling, uint32_t *fl);
int x2_cmp_pred(uint32_t a, uint32_t b, int imm, const x2env *e, uint32_t *fl);   /* 0/1 */
void x2_comis(uint32_t a, uint32_t b, const x2env *e, int signalling, int *zf, int *pf, int *cf,
              uint32_t *fl);
uint32_t x2_cvt_i2f(uint32_t i, const x2env *e, uint32_t *fl);
uint32_t x2_cvt_i64_2f(uint64_t i, const x2env *e, uint32_t *fl);   /* CVTSI2SS r64 (2026-10-23) */
uint32_t x2_cvt_f2i(uint32_t b, const x2env *e, int trunc, uint32_t *fl);
uint32_t x2_cvt_h2f(uint32_t h, const x2env *e, uint32_t *fl);

/* integer helpers (int_ops.py), on 512-bit little-endian byte arrays */
typedef union { uint8_t b[64]; uint16_t w[32]; uint32_t d[16]; uint64_t q[8]; } x2reg;

uint16_t x2_maddubs_word(uint8_t a0, uint8_t a1, uint8_t b0, uint8_t b1);   /* one (V)PMADDUBSW word lane */
uint32_t x2_dpbusd_lane(uint32_t acc, const uint8_t *a4, const uint8_t *b4, int saturate);  /* one VPDPBUSD(S) lane */
void x2_pmaddubsw(const x2reg *a, const x2reg *b, int vl, x2reg *r);
void x2_pmaddwd(const x2reg *a, const x2reg *b, int vl, x2reg *r);
void x2_pdpbusd(const x2reg *acc, const x2reg *a, const x2reg *b, int vl, int saturate, x2reg *r);
void x2_phaddd(const x2reg *a, const x2reg *b, int vl, x2reg *r);
void x2_masked(const x2reg *res, const x2reg *dst, uint64_t k, int z, int vl, int eb, x2reg *r);

/* ------------------------------------------------------------------ entry-level prediction */
enum { X2B_PACKED_FP2 = 1, X2B_SCALAR_FP2, X2B_PACKED_FP1, X2B_CMP_K, X2B_CMP_VEC, X2B_COMIS,
       X2B_CVT_F2I_GPR, X2B_CVT_I2F_SCALAR, X2B_INT2, X2B_INT_ACC,
       X2B_CMP_SCALAR /* 11, added 2026-10-23: (V)CMPSS into an xmm lane 0 */ };
enum { X2F_NONE = 0, X2F_ADD, X2F_SUB, X2F_MUL, X2F_DIV, X2F_MAX, X2F_MIN, X2F_CMP, X2F_CVT_I2F,
       X2F_CVT_F2I, X2F_CVT_H2F, X2F_PMADDUBSW, X2F_PMADDWD, X2F_PHADDD, X2F_PDPBUSD,
       X2F_CVT_I64_2F /* 15, added 2026-10-23 */ };
enum { X2E_LEGACY = 0, X2E_VEX = 1, X2E_EVEX = 2 };
enum { X2M_NONE = 0, X2M_MERGE = 1, X2M_ZERO = 2 };
enum { X2D_VEC = 0, X2D_K = 1, X2D_RFLAGS = 2, X2D_GPR = 3 };

/* What one stub executes; generated by stubgen.py from the table entry and the operand variant. */
typedef struct {
    int builder, fn, encoding, vl, scalar;
    int maskmode;        /* X2M_*: NONE = k0 / no masking (VEX, legacy, EVEX plain)     */
    int er;              /* -1, or the {er} rounding mode 0..3                            */
    int sae;             /* {sae} without {er}                                            */
    int mem, bcast, imm; /* imm: -1 if none                                               */
    int trunc, signalling, src_eb, dst_eb, saturate;
    int dst_kind;        /* X2D_*                                                         */
} x2sem;

/* The harness case and output blocks (ABI shared with the MASM stubs; offsets are fixed). */
#pragma pack(push, 1)
typedef struct {
    uint32_t mxcsr;      /*   0 */
    uint32_t pad0;       /*   4 */
    uint64_t k;          /*   8  write mask, loaded into k1 with KMOVQ          */
    uint64_t mem_ptr;    /*  16  RAX for memory forms (driver fills it)          */
    uint64_t rflags_in;  /*  24  RFLAGS before (U)COMISS                         */
    uint64_t gpr_in;     /*  32  RAX for GPR-operand forms                      */
    uint64_t kdst_in;    /*  40  k2 before a compare into a mask                 */
    uint8_t rsv[16];     /*  48 */
    x2reg src1;          /*  64 */
    x2reg src2;          /* 128 */
    x2reg dst_old;       /* 192 */
} x2case;                /* 256 bytes */
typedef struct {
    x2reg dst;           /*   0  full 512-bit destination register                */
    uint32_t mxcsr;      /*  64  MXCSR after                                      */
    uint32_t pad0;       /*  68 */
    uint64_t rflags;     /*  72 */
    uint64_t kdst;       /*  80 */
    uint64_t gpr;        /*  88 */
    uint8_t rsv[32];     /*  96 */
} x2out;                 /* 128 bytes */
#pragma pack(pop)

#define X2_RFLAGS_OBS 0x8D5u   /* OF SF ZF AF PF CF */

/* Predict the stub's observable output. Returns 0, or -1 if the case is outside the model. */
int x2_predict(const x2sem *s, const x2case *c, x2out *o);

/* Number of lane cases one execution of this stub carries (for the budget's counting unit). */
int x2_lanes(const x2sem *s);

#endif
