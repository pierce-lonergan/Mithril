"""Write build_info.h: sha256 of the interpreter sources and of the harness sources (line endings
normalised to LF), so every results file names the code that produced it (FUZZ-DESIGN §1).

  python -I mkbuildinfo.py SRC_DIR OUT_HEADER [NAME=FILE ...]

Each NAME=FILE adds `#define X2_<NAME>_SRC_SHA256` over that one file (LF-normalised), e.g.
PROVE=..\\proofs\\x2prove.c for the proof tool (added 2026-10-16 after review: exhaustive.json must name
the code that produced it).
"""
import hashlib
import os
import sys

INTERP = ["x2ref.h", "x2ref.c"]
HARNESS = ["x2harness.h", "x2fuzz.c", "x2sha256.h", "x2sha256.c", "x2probe.asm", "stubgen.py"]


def digest(src, names):
    h = hashlib.sha256()
    for n in names:
        with open(os.path.join(src, n), "rb") as f:
            data = f.read().replace(b"\r\n", b"\n")
        h.update(n.encode() + b"\0" + hashlib.sha256(data).digest())
    return h.hexdigest()


def file_digest(path):
    with open(path, "rb") as f:
        return hashlib.sha256(f.read().replace(b"\r\n", b"\n")).hexdigest()


def main():
    src, out = sys.argv[1], sys.argv[2]
    i, hs = digest(src, INTERP), digest(src, HARNESS)
    extra = []
    for spec in sys.argv[3:]:
        name, path = spec.split("=", 1)
        extra.append((name.upper(), file_digest(path)))
    with open(out, "w", newline="\n") as f:
        f.write("/* GENERATED by mkbuildinfo.py */\n#define X2_STR2(x) #x\n#define X2_STR(x) X2_STR2(x)\n")
        f.write('#define X2_INTERP_SRC_SHA256 "%s"\n#define X2_HARNESS_SRC_SHA256 "%s"\n' % (i, hs))
        for name, d in extra:
            f.write('#define X2_%s_SRC_SHA256 "%s"\n' % (name, d))
        f.write('#define X2_COMPILER "MSVC _MSC_FULL_VER=" X2_STR(_MSC_FULL_VER)\n')
    print("interp_src_sha256", i)
    print("harness_src_sha256", hs)
    for name, d in extra:
        print("%s_src_sha256" % name.lower(), d)


if __name__ == "__main__":
    main()
