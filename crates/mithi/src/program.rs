/// std_platform names that exist but are outside the X1 prelude (note section 12): a use is
/// E-OUT-OF-SCOPE-<NAME>.
pub const OOS_PLATFORM_NAMES: &[&str] = &["MemCap", "Root", "Fs", "File", "Spawner", "Blob", "Pool"];
/// Format codes in the X1 list (Hearth's Q4, Q8, F16, BF16 and F32 blocks).
pub const X1_FORMAT_CODES: &[&str] = &["f16", "bf16", "f32", "i8", "u8", "i16", "u16", "i32", "u32", "nibbles"];

pub fn split_path(s: &str) -> Vec<String> {
    s.split("::").filter(|x| !x.is_empty()).map(|x| x.to_string()).collect()
}

pub fn join_path(module: &str, name: &str) -> String {
    if module.is_empty() {
        name.to_string()
    } else {
        format!("{module}::{name}")
    }
}

pub fn parse_range_attr(a: &Attr) -> Option<(i128, i128)> {
    // "-127..=127" or "0..=511" or "0..512"
    let s = a.args.first()?.replace(' ', "");
    let (lo, hi, incl) = if let Some(i) = s.find("..=") {
        (&s[..i], &s[i + 3..], true)
    } else if let Some(i) = s.find("..") {
        (&s[..i], &s[i + 2..], false)
    } else {
        return None;
    };
    let p = |x: &str| -> Option<i128> {
        let x = x.replace('_', "");
        let x = x.trim_end_matches(|c: char| c.is_ascii_alphabetic() || c.is_ascii_digit() && false);
        x.parse::<i128>().ok()
    };
    let lo = p(lo)?;
    let mut hi = p(hi)?;
    if !incl {
        hi -= 1;
    }
    Some((lo, hi))
}

impl Program {
    pub fn new(sm: SourceMap) -> Program {
        Program {
            sm,
            adts: vec![],
            traits: vec![],
            impls: vec![],
            fns: vec![],
            consts: vec![],
            formats: vec![],
            schedules: vec![],
            specs: vec![],
            evidences: vec![],
            seams: vec![],
            targets: vec![],
            aliases: vec![],
            names: HashMap::new(),
            oos: vec![],
            path_attrs: vec![],
            diags: vec![],
            lang_adts: HashMap::new(),
            lang_traits: HashMap::new(),
            loose: vec![],
            invariant_decls: vec![],
            modules: vec![String::new()],
            impls_of_trait: HashMap::new(),
        }
    }

    pub fn lang_adt(&self, n: &str) -> AdtId {
        *self.lang_adts.get(n).unwrap_or_else(|| panic!("missing lang adt {n}"))
    }
    pub fn lang_trait(&self, n: &str) -> TraitId {
        *self.lang_traits.get(n).unwrap_or_else(|| panic!("missing lang trait {n}"))
    }
    pub fn try_lang_trait(&self, n: &str) -> Option<TraitId> {
        self.lang_traits.get(n).copied()
    }
    pub fn opt_ty(&self, t: Ty) -> Ty {
        Ty::Adt(self.lang_adt("Option"), vec![t])
    }
    pub fn is_lang_adt(&self, t: &Ty, n: &str) -> bool {
        matches!(t, Ty::Adt(a, _) if self.lang_adts.get(n) == Some(a))
    }

    pub fn ty_name(&self, t: &Ty) -> String {
        match t {
            Ty::Adt(a, v) => {
                let mut s = self.adts[*a as usize].name.clone();
                if !v.is_empty() {
                    s.push('<');
                    s.push_str(&v.iter().map(|x| self.ty_name(x)).collect::<Vec<_>>().join(", "));
                    s.push('>');
                }
                s
            }
            Ty::Ref(m, i) => format!("&{}{}", if *m { "mut " } else { "" }, self.ty_name(i)),
            Ty::Slice(i) => format!("[{}]", self.ty_name(i)),
            Ty::Array(i, n) => format!("[{}; {}]", self.ty_name(i), self.ty_name(n)),
            Ty::Tuple(v) => {
                if v.is_empty() {
                    "()".into()
                } else {
                    format!("({}{})", v.iter().map(|x| self.ty_name(x)).collect::<Vec<_>>().join(", "), if v.len() == 1 { "," } else { "" })
                }
            }
            Ty::Assoc(b, tr, n) => format!("<{} as {}>::{}", self.ty_name(b), self.traits[*tr as usize].name, n),
            Ty::Opaque(bs) => format!("impl {}", bs.iter().map(|(t, _)| self.traits[*t as usize].name.clone()).collect::<Vec<_>>().join(" + ")),
            Ty::FnPtr(p, r) => format!("fn({}) -> {}", p.iter().map(|x| self.ty_name(x)).collect::<Vec<_>>().join(", "), self.ty_name(r)),
            _ => format!("{t}"),
        }
    }

    // ------------------------------------------------------------------ collection
    pub fn collect_file(&mut self, items: &[Item], module: &str, role: FileRole) {
        if !self.modules.iter().any(|m| m == module) {
            self.modules.push(module.to_string());
        }
        // pass 1: declare names
        for it in items {
            self.declare(it, module, role);
        }
    }

    fn declare(&mut self, it: &Item, module: &str, role: FileRole) {
        match it {
            Item::Struct(s) => {
                let path = join_path(module, &s.name.name);
                let lang = attr_value(&s.attrs, "lang");
                let builtin = attr_value(&s.attrs, "builtin_type");
                let kind = if let Some(b) = builtin.clone().or_else(|| if s.attrs.iter().any(|a| a.name == "builtin_type") { Some(s.name.name.clone()) } else { None }) {
                    AdtKind::Builtin(b)
                } else if s.opaque {
                    AdtKind::Opaque
                } else {
                    AdtKind::Struct
                };
                let partial = role != FileRole::User && s.opaque;
                let derives = derives_of(&s.attrs);
                let id = self.adts.len() as AdtId;
                self.adts.push(AdtDef {
                    name: s.name.name.clone(),
                    path: path.clone(),
                    module: module.to_string(),
                    kind,
                    generics: vec![],
                    variants: vec![],
                    linear: s.linear,
                    derives,
                    attrs: s.attrs.clone(),
                    span: s.span,
                    role,
                    partial,
                    from_format: s.attrs.iter().any(|a| a.name == "format_struct" || a.name == "format_derived"),
                    invariant: None,
                    lang: lang.clone(),
                });
                self.define(&path, Def::Adt(id), s.name.span);
                if let Some(l) = lang {
                    self.lang_adts.insert(l, id);
                } else if role == FileRole::Std {
                    self.lang_adts.entry(s.name.name.clone()).or_insert(id);
                }
            }
            Item::Enum(e) => {
                let path = join_path(module, &e.name.name);
                let lang = attr_value(&e.attrs, "lang");
                let id = self.adts.len() as AdtId;
                self.adts.push(AdtDef {
                    name: e.name.name.clone(),
                    path: path.clone(),
                    module: module.to_string(),
                    kind: AdtKind::Enum,
                    generics: vec![],
                    variants: vec![],
                    linear: false,
                    derives: derives_of(&e.attrs),
                    attrs: e.attrs.clone(),
                    span: e.span,
                    role,
                    partial: false,
                    from_format: false,
                    invariant: None,
                    lang: lang.clone(),
                });
                self.define(&path, Def::Adt(id), e.name.span);
                for (i, v) in e.variants.iter().enumerate() {
                    self.define(&format!("{path}::{}", v.name.name), Def::Variant(id, i as u32), v.name.span);
                }
                if let Some(l) = lang {
                    self.lang_adts.insert(l, id);
                } else if role == FileRole::Std {
                    self.lang_adts.entry(e.name.name.clone()).or_insert(id);
                }
            }
            Item::Trait(t) => {
                let path = join_path(module, &t.name.name);
                let lang = attr_value(&t.attrs, "lang");
                let id = self.traits.len() as TraitId;
                self.traits.push(TraitDef {
                    name: t.name.name.clone(),
                    path: path.clone(),
                    generics: vec![],
                    assoc_types: vec![],
                    methods: BTreeMap::new(),
                    consts: BTreeMap::new(),
                    supers: vec![],
                    span: t.span,
                    role,
                    lang: lang.clone(),
                });
                self.define(&path, Def::Trait(id), t.name.span);
                if let Some(l) = lang {
                    self.lang_traits.insert(l, id);
                } else if role == FileRole::Std {
                    self.lang_traits.entry(t.name.name.clone()).or_insert(id);
                }
            }
            Item::Format(f) => {
                // the struct and its accessors are generated source (lower::gen_formats), declared
                // from that generated file; here only the format record is kept
                self.formats.push(FormatInfo { adt: u32::MAX, decl: f.clone(), module: module.to_string(), size: None });
            }
            Item::Mod(m) => {
                let sub = join_path(module, &m.name.name);
                if let Some(sp) = m.path_attr {
                    self.path_attrs.push(sp);
                }
                self.define(&sub, Def::Mod, m.name.span);
                self.collect_file(&m.items, &sub, role);
            }
            Item::Use(u) => {
                for p in &u.tree {
                    let segs: Vec<String> = p.segs.iter().map(|s| s.ident.name.clone()).collect();
                    if segs.last().map(|s| s == "*").unwrap_or(false) {
                        // glob imports: record as alias of the module (resolution falls back anyway)
                        continue;
                    }
                    let (target, local) = if let Some(last) = segs.last() {
                        if let Some(alias) = last.strip_prefix("as ") {
                            (segs[..segs.len() - 1].join("::"), alias.to_string())
                        } else {
                            (segs.join("::"), last.clone())
                        }
                    } else {
                        continue;
                    };
                    let key = join_path(module, &local);
                    if !self.names.contains_key(&key) {
                        self.names.insert(key, Def::Alias(target));
                    }
                }
            }
            Item::Const(c) => {
                let path = join_path(module, &c.name.name);
                let id = self.consts.len() as u32;
                self.consts.push(ConstDef {
                    name: c.name.name.clone(),
                    path: path.clone(),
                    ty: Ty::Error,
                    value: c.value.clone(),
                    is_static: c.is_static,
                    is_mut: c.is_mut,
                    span: c.span,
                    role,
                    module: module.to_string(),
                    attrs: c.attrs.clone(),
                    builtin: None,
                    builtin_float: None,
                });
                self.define(&path, Def::Const(id), c.name.span);
            }
            Item::TypeAlias(n, g, t, _sp) => {
                let path = join_path(module, &n.name);
                let id = self.aliases.len() as u32;
                self.aliases.push((split_path(&path), t.clone(), module.to_string(), g.clone()));
                self.define(&path, Def::TypeAlias(id), n.span);
            }
            Item::Schedule(s) => {
                let path = join_path(module, &s.name.name);
                let id = self.schedules.len() as u32;
                self.schedules.push((s.clone(), module.to_string()));
                self.define(&path, Def::Schedule(id), s.name.span);
                // schedules are also visible at the root (spec claims name them unqualified)
                self.names.entry(s.name.name.clone()).or_insert(Def::Schedule(id));
            }
            Item::Spec(s) => {
                self.specs.push((s.clone(), module.to_string()));
            }
            Item::Evidence(e) => {
                let mut ev = Evidence { name: e.name.text(), kind: String::new(), subject: String::new(), grade: String::new(), span: e.span };
                for (k, v) in &e.fields {
                    match k.name.as_str() {
                        "kind" => ev.kind = v.text(),
                        "subject" => ev.subject = v.text(),
                        "grade" => ev.grade = v.text(),
                        _ => {}
                    }
                }
                self.evidences.push(ev);
            }
            Item::Seam(s) => {
                for f in &s.fns {
                    self.names.insert(format!("{}::{}", s.name.name, f.name), Def::SeamFn(format!("{}::{}", s.name.name, f.name)));
                }
                self.names.insert(s.name.name.clone(), Def::Mod);
                self.seams.push(s.clone());
            }
            Item::Target(t) => self.targets.push(t.clone()),
            Item::OutOfScope(o) => self.oos.push((o.kw.clone(), o.span)),
            Item::LooseStmts(stmts, sp) => self.loose.push((stmts.clone(), *sp, module.to_string())),
            Item::Invariant(inv) => self.invariant_decls.push((inv.clone(), module.to_string(), role)),
            Item::Fn(_) | Item::Impl(_) | Item::MacroRules(_) => {}
        }
    }

    fn define(&mut self, path: &str, d: Def, sp: Span) {
        if let Some(old) = self.names.get(path) {
            if *old != d && !matches!(old, Def::Alias(_)) {
                self.diags.push(Diag::new("E-TYPE", sp, format!("`{path}` is defined more than once")));
                return;
            }
        }
        self.names.insert(path.to_string(), d);
    }

    // ------------------------------------------------------------------ resolution
    /// Resolve a path written in `module`. Lookup order: the module, then its ancestors
    /// (mithi treats every enclosing module as glob-imported, a documented deviation used only
    /// for prelude modules), then the std prelude namespace `std::prelude`.
    pub fn resolve(&self, module: &str, segs: &[String]) -> Option<Def> {
        if segs.is_empty() {
            return None;
        }
        let mut seen = 0;
        self.resolve_inner(module, segs, &mut seen)
    }

    fn resolve_inner(&self, module: &str, segs: &[String], depth: &mut u32) -> Option<Def> {
        *depth += 1;
        if *depth > 16 {
            return None;
        }
        let full = segs.join("::");
        let mut m = module.to_string();
        loop {
            let key = join_path(&m, &full);
            if let Some(d) = self.names.get(&key) {
                return self.follow(d.clone(), depth);
            }
            // first segment is an alias (use)? then expand
            if segs.len() > 1 {
                if let Some(Def::Alias(t)) = self.names.get(&join_path(&m, &segs[0])) {
                    let mut ns = split_path(t);
                    ns.extend_from_slice(&segs[1..]);
                    if let Some(d) = self.resolve_inner("", &ns, depth) {
                        return Some(d);
                    }
                }
            }
            if m.is_empty() {
                break;
            }
            m = match m.rfind("::") {
                Some(i) => m[..i].to_string(),
                None => String::new(),
            };
        }
        // std prelude
        let key = format!("std::prelude::{full}");
        if let Some(d) = self.names.get(&key) {
            return self.follow(d.clone(), depth);
        }
        // primitive type names
        if segs.len() == 1 && is_prim_name(&segs[0]) {
            return Some(Def::Prim(segs[0].clone()));
        }
        None
    }

    fn follow(&self, d: Def, depth: &mut u32) -> Option<Def> {
        match d {
            Def::Alias(t) => {
                let segs = split_path(&t);
                self.resolve_inner("", &segs, depth).or_else(|| {
                    // `use std::cmp::Reverse` where std items live under `std::cmp`
                    None
                })
            }
            d => Some(d),
        }
    }

    // ------------------------------------------------------------------ type lowering
    pub fn lower_ty(&mut self, t: &TypeAst, cx: &TyCx, module: &str) -> Ty {
        match &t.kind {
            TypeKind::Ref { mutable, lifetime, inner } => {
                if let Some(l) = lifetime {
                    if l != "static" || true {
                        self.diags.push(Diag::new("E-LIFETIME", t.span, format!("lifetime `'{l}`: references are second-class and lifetimes do not exist (FF-REF)")));
                    }
                }
                Ty::Ref(*mutable, Box::new(self.lower_ty(inner, cx, module)))
            }
            TypeKind::Slice(i) => Ty::Slice(Box::new(self.lower_ty(i, cx, module))),
            TypeKind::Array(i, n) => {
                let et = self.lower_ty(i, cx, module);
                let nt = self.lower_const_expr(n, cx, module);
                Ty::Array(Box::new(et), Box::new(nt))
            }
            TypeKind::Tuple(v) => {
                if v.is_empty() {
                    Ty::Unit
                } else {
                    Ty::Tuple(v.iter().map(|x| self.lower_ty(x, cx, module)).collect())
                }
            }
            TypeKind::Never => Ty::Never,
            TypeKind::Infer => Ty::Error,
            TypeKind::RawPtr(..) => {
                self.diags.push(Diag::new("E-GRANT-UNSAFE", t.span, "raw pointer types exist only in packages granted `unsafe` (FF-UNSAFE)"));
                Ty::Error
            }
            TypeKind::DynTrait(_) => {
                self.diags.push(Diag::new("E-DYN", t.span, "`dyn Trait`: no dynamic dispatch in v1; use a generic parameter (FF-DYN, DR-005)"));
                Ty::Error
            }
            TypeKind::FnPtr(ps, r) => {
                let p = ps.iter().map(|x| self.lower_ty(x, cx, module)).collect();
                let r = r.as_ref().map(|x| self.lower_ty(x, cx, module)).unwrap_or(Ty::Unit);
                Ty::FnPtr(p, Box::new(r))
            }
            TypeKind::ImplTrait(bs) => {
                let mut out = vec![];
                for b in bs {
                    match b {
                        Bound::Trait(p) => {
                            if let Some((tr, _args, assoc)) = self.lower_trait_ref(p, cx, module) {
                                out.push((tr, assoc));
                            }
                        }
                        Bound::FnTrait { kind, .. } => {
                            if let Some(tr) = self.try_lang_trait(kind) {
                                out.push((tr, vec![]));
                            }
                        }
                        Bound::Lifetime(l, sp) => {
                            self.diags.push(Diag::new("E-LIFETIME", *sp, format!("lifetime bound `'{l}` (FF-REF)")));
                        }
                        _ => {}
                    }
                }
                if cx.impl_trait_arg {
                    // argument position: an anonymous generic parameter, registered by the caller
                    Ty::Opaque(out)
                } else {
                    Ty::Opaque(out)
                }
            }
            TypeKind::QPath(base, tr, name) => {
                let b = self.lower_ty(base, cx, module);
                match self.lower_trait_ref(tr, cx, module) {
                    Some((tid, _, _)) => Ty::Assoc(Box::new(b), tid, name.name.clone()),
                    None => Ty::Error,
                }
            }
            TypeKind::Path(p) => self.lower_path_ty(p, cx, module, t.span),
        }
    }

    pub fn lower_const_expr(&mut self, e: &ast::Expr, cx: &TyCx, module: &str) -> Ty {
        match &e.kind {
            ast::ExprKind::Lit(ast::Lit::Int(v, _)) => Ty::Const(*v as i128),
            ast::ExprKind::Path(p) if p.segs.len() == 1 => {
                if let Some(i) = cx.params.iter().position(|g| g == &p.segs[0].ident.name) {
                    return Ty::Param(i as u32);
                }
                if let Some(Def::Const(c)) = self.resolve(module, &[p.segs[0].ident.name.clone()]) {
                    if let Some(v) = self.const_int_value(c) {
                        return Ty::Const(v);
                    }
                }
                self.diags.push(Diag::new("E-TYPE", e.span, "array length must be a constant"));
                Ty::Error
            }
            ast::ExprKind::Block(b) if b.stmts.is_empty() && b.tail.is_some() => self.lower_const_expr(b.tail.as_ref().unwrap(), cx, module),
            ast::ExprKind::Binary(op, a, b) => {
                let x = self.lower_const_expr(a, cx, module);
                let y = self.lower_const_expr(b, cx, module);
                match (x, y) {
                    (Ty::Const(x), Ty::Const(y)) => Ty::Const(match op {
                        ast::BinOp::Add => x + y,
                        ast::BinOp::Sub => x - y,
                        ast::BinOp::Mul => x * y,
                        ast::BinOp::Div if y != 0 => x / y,
                        ast::BinOp::Shl => x << (y as u32 % 127),
                        _ => {
                            self.diags.push(Diag::new("E-TYPE", e.span, "unsupported constant expression"));
                            return Ty::Error;
                        }
                    }),
                    _ => Ty::Error,
                }
            }
            _ => {
                self.diags.push(Diag::new("E-TYPE", e.span, "unsupported constant expression in a type"));
                Ty::Error
            }
        }
    }

    pub fn const_int_value(&self, c: u32) -> Option<i128> {
        let cd = &self.consts[c as usize];
        if let Some(v) = cd.builtin {
            return Some(v);
        }
        match cd.value.as_ref().map(|e| &e.kind) {
            Some(ast::ExprKind::Lit(ast::Lit::Int(v, _))) => Some(*v as i128),
            _ => None,
        }
    }

    pub fn lower_path_ty(&mut self, p: &ast::Path, cx: &TyCx, module: &str, span: Span) -> Ty {
        let names: Vec<String> = p.segs.iter().map(|s| s.ident.name.clone()).collect();
        // generic params and Self
        if names.len() == 1 {
            let n = &names[0];
            if n == "Self" {
                if let Some(st) = &cx.self_ty {
                    return st.clone();
                }
            }
            if let Some(i) = cx.params.iter().position(|g| g == n) {
                return Ty::Param(i as u32);
            }
            if n.starts_with('\'') {
                return Ty::Error;
            }
        }
        // Self::Item, T::Item
        if names.len() == 2 && p.segs[0].generics.is_none() {
            let base = &names[0];
            let base_ty = if base == "Self" {
                cx.self_ty.clone()
            } else {
                cx.params.iter().position(|g| g == base).map(|i| Ty::Param(i as u32))
            };
            if let Some(bt) = base_ty {
                // find a trait with this associated type among the bounds (or the enclosing trait)
                let an = names[1].clone();
                if let Some(tr) = self.assoc_owner(&bt, &an, cx) {
                    return Ty::Assoc(Box::new(bt), tr, an);
                }
                self.diags.push(Diag::new("E-TYPE", span, format!("no associated type `{an}` in scope")));
                return Ty::Error;
            }
        }
        // out-of-scope std_platform names (note section 12)
        if let Some(last) = names.last() {
            if OOS_PLATFORM_NAMES.contains(&last.as_str()) && self.resolve(module, &names).is_none() {
                self.oos.push((last.to_uppercase(), p.segs.last().unwrap().ident.span));
                return Ty::Error;
            }
        }
        let def = self.resolve(module, &names);
        let args: Vec<Ty> = match &p.segs.last().unwrap().generics {
            Some(ga) => ga
                .iter()
                .filter_map(|g| match g {
                    GenericArg::Type(t) => {
                        if let TypeKind::Path(pp) = &t.kind {
                            if pp.segs.len() == 1 && pp.segs[0].ident.name.starts_with('\'') {
                                self.diags.push(Diag::new("E-LIFETIME", t.span, "lifetime arguments do not exist (FF-REF)"));
                                return None;
                            }
                        }
                        Some(self.lower_ty(t, cx, module))
                    }
                    GenericArg::Const(e) => Some(self.lower_const_expr(e, cx, module)),
                    GenericArg::Binding(..) => None,
                })
                .collect(),
            None => vec![],
        };
        match def {
            Some(Def::Prim(n)) => prim_ty(&n).unwrap_or(Ty::Error),
            Some(Def::Adt(a)) => {
                let want = self.adts[a as usize].generics.len();
                let mut args = args;
                if args.len() < want {
                    // missing arguments: inference variables are not available here
                    if !args.is_empty() || !cx.allow_missing_args {
                        self.diags.push(Diag::new("E-TYPE", span, format!("`{}` takes {} generic argument(s), {} given", self.adts[a as usize].name, want, args.len())));
                    }
                    while args.len() < want {
                        args.push(Ty::Error);
                    }
                }
                args.truncate(want);
                Ty::Adt(a, args)
            }
            Some(Def::TypeAlias(i)) => {
                let (_, t, m, _) = self.aliases[i as usize].clone();
                self.lower_ty(&t, &TyCx::default(), &m)
            }
            Some(Def::Trait(_)) => {
                self.diags.push(Diag::new("E-DYN", span, "a bare trait used as a type is a trait object: no dynamic dispatch (FF-DYN)"));
                Ty::Error
            }
            _ => {
                let n = p.text();
                if is_dc_type(&n) {
                    self.diags.push(Diag::new("E-FF-CELL", span, format!("`{n}`: interior mutability and shared ownership are rejected; use Mutex<T>::with_lock, Frozen<T> or index-based structures (FF-CELL)")));
                } else {
                    self.diags.push(Diag::new("E-UNRESOLVED", span, format!("cannot find type `{n}` in this scope")));
                }
                Ty::Error
            }
        }
    }

    fn assoc_owner(&self, bt: &Ty, name: &str, cx: &TyCx) -> Option<TraitId> {
        if let Some(t) = cx.in_trait {
            if self.traits[t as usize].assoc_types.iter().any(|a| a == name) {
                return Some(t);
            }
        }
        if let Ty::Param(i) = bt {
            if let Some(bs) = cx.bounds.get(*i as usize) {
                for b in bs {
                    if let BoundDef::Trait { tr, .. } = b {
                        if self.traits[*tr as usize].assoc_types.iter().any(|a| a == name) {
                            return Some(*tr);
                        }
                    }
                }
            }
        }
        // impl of a trait with this assoc type for Self
        if let Some(tr) = cx.impl_trait {
            if self.traits[tr as usize].assoc_types.iter().any(|a| a == name) {
                return Some(tr);
            }
        }
        // any trait with this associated type (Iterator::Item is the common case)
        self.traits.iter().position(|t| t.assoc_types.iter().any(|a| a == name)).map(|i| i as TraitId)
    }

    pub fn lower_trait_ref(&mut self, p: &ast::Path, cx: &TyCx, module: &str) -> Option<(TraitId, Vec<Ty>, Vec<(String, Ty)>)> {
        let names: Vec<String> = p.segs.iter().map(|s| s.ident.name.clone()).collect();
        match self.resolve(module, &names) {
            Some(Def::Trait(t)) => {
                let mut args = vec![];
                let mut assoc = vec![];
                if let Some(ga) = &p.segs.last().unwrap().generics {
                    for g in ga {
                        match g {
                            GenericArg::Type(t) => args.push(self.lower_ty(t, cx, module)),
                            GenericArg::Binding(n, t) => assoc.push((n.name.clone(), self.lower_ty(t, cx, module))),
                            GenericArg::Const(e) => args.push(self.lower_const_expr(e, cx, module)),
                        }
                    }
                }
                Some((t, args, assoc))
            }
            _ => {
                let n = p.text();
                if n == "Drop" {
                    // handled by the impl check (E-DROP-IMPL)
                    return None;
                }
                self.diags.push(Diag::new("E-UNRESOLVED", p.span, format!("cannot find trait `{n}`")));
                None
            }
        }
    }

    pub fn lower_bounds(&mut self, bs: &[Bound], cx: &TyCx, module: &str, out: &mut GParam) {
        for b in bs {
            match b {
                Bound::Trait(p) => {
                    let n = p.text();
                    if n == "Local" || n == "Linear" {
                        continue;
                    }
                    if let Some((tr, args, assoc)) = self.lower_trait_ref(p, cx, module) {
                        out.bounds.push(BoundDef::Trait { tr, args, assoc });
                    }
                }
                Bound::FnTrait { kind, params, ret, .. } => {
                    let k = match kind.as_str() {
                        "Fn" => 0,
                        "FnMut" => 1,
                        _ => 2,
                    };
                    let ps = params.iter().map(|t| self.lower_ty(t, cx, module)).collect();
                    let r = ret.as_ref().map(|t| self.lower_ty(t, cx, module)).unwrap_or(Ty::Unit);
                    out.bounds.push(BoundDef::Fn { kind: k, params: ps, ret: r });
                }
                Bound::Maybe(p) => match p.last() {
                    "Local" => out.relax_local = true,
                    "Linear" => out.relax_linear = true,
                    _ => {}
                },
                Bound::Lifetime(l, sp) => {
                    self.diags.push(Diag::new("E-LIFETIME", *sp, format!("lifetime bound `'{l}` (FF-REF)")));
                }
            }
        }
    }
}

/// Type-lowering context: generic parameter names (by index) and `Self`.
#[derive(Default, Clone)]
pub struct TyCx {
    pub params: Vec<String>,
    pub bounds: Vec<Vec<BoundDef>>,
    pub self_ty: Option<Ty>,
    pub in_trait: Option<TraitId>,
    pub impl_trait: Option<TraitId>,
    pub impl_trait_arg: bool,
    pub allow_missing_args: bool,
}

pub fn is_prim_name(s: &str) -> bool {
    prim_ty(s).is_some()
}

pub fn prim_ty(s: &str) -> Option<Ty> {
    if let Some(i) = IntTy::from_name(s) {
        return Some(Ty::Int(i));
    }
    Some(match s {
        "f32" => Ty::F32,
        "f64" => Ty::F64,
        "f16" => Ty::F16,
        "bf16" => Ty::Bf16,
        "bool" => Ty::Bool,
        "char" => Ty::Char,
        "str" => Ty::Str,
        _ => return None,
    })
}

pub fn is_dc_type(n: &str) -> bool {
    let last = n.rsplit("::").next().unwrap_or(n);
    matches!(last, "Cell" | "RefCell" | "Rc" | "Weak" | "UnsafeCell" | "OnceCell")
}

pub fn attr_value(attrs: &[Attr], name: &str) -> Option<String> {
    attrs.iter().find(|a| a.name == name).and_then(|a| a.args.first()).map(|s| s.trim_matches('"').to_string())
}

pub fn derives_of(attrs: &[Attr]) -> Vec<String> {
    let mut out = vec![];
    for a in attrs {
        if a.name == "derive" {
            for x in &a.args {
                out.push(x.rsplit("::").next().unwrap_or(x).trim().to_string());
            }
        }
    }
    out
}
