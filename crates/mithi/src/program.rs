#[derive(Clone, Debug, PartialEq, Eq)]
pub enum AdtKind {
    Struct,
    Enum,
    /// builtin std type implemented natively (Vec, Mutex, Iter, ...)
    Builtin(String),
    /// declared without a body in a prelude (`struct Store { … }` with every field elided)
    Opaque,
}

#[derive(Clone, Debug)]
pub struct AdtDef {
    pub name: String,
    pub path: String,
    pub module: String,
    pub kind: AdtKind,
    pub generics: Vec<GParam>,
    pub variants: Vec<VariantDef>,
    pub linear: bool,
    pub derives: Vec<String>,
    pub attrs: Vec<Attr>,
    pub span: Span,
    pub role: FileRole,
    /// fields elided with `…`: the declaration is partial
    pub partial: bool,
    /// a struct generated by a `format` item
    pub from_format: bool,
    pub invariant: Option<FnId>,
    pub lang: Option<String>,
}

impl AdtDef {
    pub fn is_struct(&self) -> bool {
        self.kind == AdtKind::Struct || self.kind == AdtKind::Opaque
    }
    pub fn has_attr(&self, n: &str) -> bool {
        self.attrs.iter().any(|a| a.name == n)
    }
    pub fn derives(&self, t: &str) -> bool {
        self.derives.iter().any(|d| d == t)
    }
}

